"""Generators: machine description -> LinuxCNC INI and firmware constants.

Both outputs carry the same fingerprint of the source machine file, so a stale
generated file can be detected mechanically rather than noticed after a crash.

The single most important property of this module is tested in
tests/unit/test_emit.py: the scale the INI tells LinuxCNC and the scale the
firmware uses MUST be the same number. If they drift, the machine moves the
wrong distance while every individual file looks correct.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

from .model import Machine, Node

GENERATED_BANNER = "DO NOT EDIT - generated by tools/machinegen from machine/wen33013.toml"


def fingerprint(path: str | Path) -> str:
    """Short content hash of the machine description."""
    data = Path(path).read_bytes()
    return hashlib.sha256(data).hexdigest()[:16]


def _ini_header(machine: Machine, fp: str) -> str:
    return "\n".join(
        [
            f"# {GENERATED_BANNER}",
            f"# machine: {machine.name} ({machine.base_machine})",
            f"# source-fingerprint: {fp}",
            "#",
            "# Regenerate with:  /regen   (or: python -m machinegen generate)",
            "",
        ]
    )


def home_sequence(machine: Machine) -> dict[str, int]:
    """Homing order: Z retracts FIRST, then the rest.

    LinuxCNC homes in ascending HOME_SEQUENCE. Emitting the axes in XYZ order
    - the obvious thing, and what this generator used to do - moves the table
    under a tool that has not been lifted yet. With a vise or a workpiece
    clamped down, the first homing run of the day crashes the cutter.

    Z is always sequence 0. Everything else follows in canonical order. See
    ADR-0006.
    """
    order: dict[str, int] = {}
    rest = [a.name for a in machine.ordered_axes if a.name != "z"]
    if any(a.name == "z" for a in machine.ordered_axes):
        order["z"] = 0
        start = 1
    else:
        start = 0
    for offset, name in enumerate(rest):
        order[name] = start + offset
    return order


def _ferror_lines(axis) -> list[str]:
    """Following-error limits, sized to the feedback that will police them.

    On a closed-loop axis the limit must sit well clear of the encoder's own
    resolution, or thermal drift and a single count of noise will trip a
    following error mid-cut. Open-loop axes keep LinuxCNC's conventional
    values, since nothing is actually measuring them.
    """
    enc_res = axis.encoder_resolution_mm
    if enc_res is None:
        return ["FERROR = 1.000", "MIN_FERROR = 0.250"]
    min_ferror = max(0.05, 10 * enc_res)
    return [
        f"# encoder resolves {enc_res * 1000:.2f} um; limits sized clear of it",
        f"FERROR = {min_ferror * 4:.3f}",
        f"MIN_FERROR = {min_ferror:.3f}",
    ]


def render_ini(machine: Machine, fp: str = "unknown") -> str:
    """Render the LinuxCNC INI."""
    m = machine
    lines = [_ini_header(m, fp)]

    lines += [
        "[EMC]",
        f"MACHINE = {m.name}",
        "VERSION = 1.1",
        "",
        "[DISPLAY]",
        "DISPLAY = axis",
        "CYCLE_TIME = 0.100",
        "POSITION_OFFSET = RELATIVE",
        "POSITION_FEEDBACK = ACTUAL",
        "MAX_FEED_OVERRIDE = 1.2",
        "PROGRAM_PREFIX = ../../nc_files",
        "",
        "[KINS]",
        f"JOINTS = {len(m.ordered_axes)}",
        "KINEMATICS = trivkins coordinates=XYZ",
        "",
        "[EMCMOT]",
        "EMCMOT = motmod",
        "COMM_TIMEOUT = 1.0",
        f"SERVO_PERIOD = {m.control.servo_period_ns}",
        "",
        "[TASK]",
        "TASK = milltask",
        "CYCLE_TIME = 0.010",
        "",
        "[RS274NGC]",
        "PARAMETER_FILE = linuxcnc.var",
        "",
        "[HAL]",
        "HALFILE = core.hal",
        "HALFILE = remora-spi.hal",
        "HALFILE = estop.hal",
        "",
        "[TRAJ]",
        "COORDINATES = XYZ",
        "LINEAR_UNITS = mm",
        "ANGULAR_UNITS = degree",
        f"DEFAULT_LINEAR_VELOCITY = {min(a.max_velocity_mm_s for a in m.ordered_axes) / 2:.3f}",
        f"MAX_LINEAR_VELOCITY = {max(a.max_velocity_mm_s for a in m.ordered_axes):.3f}",
        "",
    ]

    sequences = home_sequence(m)
    for index, axis in enumerate(m.ordered_axes):
        upper = axis.name.upper()
        lines += [
            f"[AXIS_{upper}]",
            f"MAX_VELOCITY = {axis.max_velocity_mm_s:.3f}",
            f"MAX_ACCELERATION = {axis.max_accel_mm_s2:.3f}",
            f"MIN_LIMIT = {axis.soft_min_mm:.3f}",
            f"MAX_LIMIT = {axis.soft_max_mm:.3f}",
            "",
            f"[JOINT_{index}]",
            "TYPE = LINEAR",
            f"# {axis.steps_per_rev} microsteps/rev over a "
            f"{axis.screw_pitch_mm} mm lead",
            f"SCALE = {axis.steps_per_mm:.6f}",
            f"MAX_VELOCITY = {axis.max_velocity_mm_s:.3f}",
            f"MAX_ACCELERATION = {axis.max_accel_mm_s2:.3f}",
            f"STEPGEN_MAXVEL = {axis.max_velocity_mm_s * 1.2:.3f}",
            f"STEPGEN_MAXACCEL = {axis.max_accel_mm_s2 * 1.25:.3f}",
            f"MIN_LIMIT = {axis.soft_min_mm:.3f}",
            f"MAX_LIMIT = {axis.soft_max_mm:.3f}",
            *_ferror_lines(axis),
            f"HOME = {axis.soft_min_mm if axis.home_direction < 0 else axis.soft_max_mm:.3f}",
            f"HOME_OFFSET = {0.0:.3f}",
            f"HOME_SEARCH_VEL = {axis.home_direction * min(5.0, axis.max_velocity_mm_s / 4):.3f}",
            f"HOME_LATCH_VEL = {axis.home_direction * 0.5:.3f}",
            "# Z retracts before the table moves under the tool - ADR-0006",
            f"HOME_SEQUENCE = {sequences[axis.name]}",
            "",
        ]

    return "\n".join(lines)


def render_firmware_header(machine: Machine, node: Node, fp: str = "unknown") -> str:
    """Render the C header one motion node's firmware compiles against.

    Each node gets only the axes it owns, so a node physically cannot command
    an axis that belongs to another board.
    """
    m = machine
    guard = f"MACHINE_CONFIG_{node.name.upper()}_H"
    # Joint indices are global (LinuxCNC numbering), so a node owning only Y
    # still reports it as joint 1. Keep the global order, filter to ours.
    node_axes = [a for a in m.ordered_axes if a.name in node.axes]
    lines = [
        f"/* {GENERATED_BANNER} */",
        f"/* machine: {m.name} ({m.base_machine}) */",
        f"/* node: {node.name}  transport: {node.transport}  cs: {node.spi_cs} */",
        f"/* source-fingerprint: {fp} */",
        "",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        f"#define NODE_SPI_CS {node.spi_cs}",
        f"#define NODE_SAFETY_INPUTS {1 if node.safety_inputs else 0}",
        f"#define AXIS_COUNT {len(node_axes)}",
        f"#define SERVO_PERIOD_US {m.control.servo_period_ns // 1000}u",
        f"#define SPI_CLOCK_HZ {m.control.spi_clock_hz}u",
        "",
        f"/* {m.driver.model} timing floor - the PIO program must not violate these */",
        f"#define STEP_PULSE_MIN_NS {int(m.driver.min_pulse_us * 1000)}u",
        f"#define DIR_SETUP_MIN_NS {int(m.driver.min_dir_setup_us * 1000)}u",
        f"#define MAX_STEP_RATE_HZ {int(m.driver.max_step_rate_hz)}u",
        "",
    ]
    global_index = {a.name: i for i, a in enumerate(m.ordered_axes)}
    for axis in node_axes:
        upper = axis.name.upper()
        index = global_index[axis.name]
        lines += [
            f"/* joint {index}: {upper} */",
            f"#define {upper}_JOINT {index}",
            f"#define {upper}_STEPS_PER_MM {axis.steps_per_mm:.6f}f",
            f"#define {upper}_MAX_STEP_RATE_HZ {axis.max_step_rate_hz:.0f}u",
            f"#define {upper}_INVERT_DIR {1 if axis.invert_direction else 0}",
        ]
        enc = axis.encoder
        if enc is None:
            lines += [f"#define {upper}_HAS_ENCODER 0", ""]
        else:
            counts_per_mm = axis.counts_per_mm
            assert counts_per_mm is not None
            lines += [
                f"#define {upper}_HAS_ENCODER 1",
                f"#define {upper}_ENCODER_BITS {enc.bits}u",
                f"#define {upper}_ENCODER_CS {enc.cs}",
                f"#define {upper}_ENCODER_COUNTS_PER_REV {enc.counts_per_rev}u",
                f"#define {upper}_ENCODER_COUNTS_PER_MM {counts_per_mm:.6f}f",
                "",
            ]
    lines += [f"#endif /* {guard} */", ""]
    return "\n".join(lines)


def render_udev_rules(machine: Machine, fp: str = "unknown") -> str:
    """Stable /dev names for USB nodes.

    Without this, two RP2040s enumerate in whatever order they powered up and
    the pendant can come back as the node you did not mean. Klipper users
    learn this the hard way; we pin by serial from the start.
    """
    lines = [
        f"# {GENERATED_BANNER}",
        f"# source-fingerprint: {fp}",
        "#",
        "# Install to /etc/udev/rules.d/99-cnc-nodes.rules then:",
        "#   sudo udevadm control --reload-rules && sudo udevadm trigger",
        "",
    ]
    for node in sorted(machine.usb_nodes, key=lambda n: n.name):
        serial = node.usb_serial or "TBD"
        lines += [
            f'# node {node.name} ({node.role})',
            f'SUBSYSTEM=="tty", ATTRS{{serial}}=="{serial}", '
            f'SYMLINK+="cnc/{node.name}", MODE="0660", GROUP="dialout"',
            "",
        ]
    if not machine.usb_nodes:
        lines.append("# (no USB nodes defined)\n")
    return "\n".join(lines)


INI_PATH = "linuxcnc/configs/wen33013/wen33013.ini"
UDEV_PATH = "pi/provision/99-cnc-nodes.rules"
FIRMWARE_HEADER_DIR = "firmware/pico-spi/include"


def firmware_header_path(node: Node) -> str:
    return f"{FIRMWARE_HEADER_DIR}/machine_config_{node.name}.h"


def generate_all(machine: Machine, repo_root: Path, fp: str) -> dict[Path, str]:
    """Render every target. Returns path -> content, writing nothing.

    One INI for LinuxCNC, one header per motion node, one udev rules file.
    """
    out: dict[Path, str] = {
        repo_root / INI_PATH: render_ini(machine, fp),
        repo_root / UDEV_PATH: render_udev_rules(machine, fp),
    }
    for node in machine.motion_nodes:
        out[repo_root / firmware_header_path(node)] = render_firmware_header(
            machine, node, fp
        )
    return out
